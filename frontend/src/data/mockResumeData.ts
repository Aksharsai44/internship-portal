export function createEmptyResumeData(student?: Student): InternResumeData {
  return {
    internId: student?.id || "",
    internName: student?.name || "Candidate Intern",
    email: student?.email || "",
    mobile: student?.mobile || "",
    location: student?.city ? `${student.city}, ${student.state || "India"}` : (student?.college || "India"),
    githubUrl: student?.githubUrl || "",
    linkedinUrl: student?.linkedinUrl || "",
    targetRole: "Software Engineering Intern",
    professionalSummary: "",
    education: student?.college ? [
      {
        id: `edu_${Date.now()}`,
        degree: student.branch ? `B.Tech in ${student.branch}` : "Bachelor of Technology",
        institution: student.college,
        period: "Enrolled",
        grade: "Candidate in good standing",
      }
    ] : [],
    experience: [],
    skills: student?.skills && student.skills.length > 0 ? student.skills : [],
    certifications: [],
    scorecard: {
      overallScore: 0,
      targetRole: "Software Engineering Intern",
      grade: "Pending Resume Upload",
      lastScannedFileName: "None",
      lastScannedDate: "N/A",
      keywordMatchRate: 0,
      matchedSkills: [],
      missingSkills: [],
      quantifiedMetricsScore: 0,
      quantifiedMetricsDetail: "Upload your resume in Resume Builder to scan ATS metrics.",
      formattingScore: 0,
      formattingDetail: "Pending document upload.",
      grammarScore: 0,
      grammarDetail: "Pending document upload.",
      bulletFixes: [],
      verificationChecklist: [],
      executiveSummary: "No resume document uploaded yet. Upload a PDF or Word document in Resume Builder to generate real-time ATS analysis.",
    },
    isSyncedToClientPortal: false,
  };
}
